// Демо-ядро AURA: локальный анализ сообщений и ответы в стиле «Джарвиса».
// Полноценное ядро подключается через Ollama (см. SYSTEM_PROMPT ниже).

export type AuraState = "idle" | "care" | "alert" | "thinking";
export type Msg = { role: "user" | "aura"; text: string; ts: number };

export const SYSTEM_PROMPT =
  "Ты — AURA, вежливый и проактивный ИИ-ассистент в стиле Джарвиса. " +
  "Отвечай на русском языке, кратко и по делу. Обращайся к собеседнику уважительно. " +
  "Если человек жалуется на самочувствие — переключайся в тёплый режим заботы. " +
  "Ты работаешь на устройстве пользователя, локально.";

const NEGATIVE =
  /(болею|болит|болеет|заболел|устал|устала|плохо|грустн|тяжело|больно|температур|кашель|насморк|голова|не могу спать|страшно|тревог|тоск)/i;
const POSITIVE =
  /(спасибо|благодарю|отлично|класс|рад(а)?|супер|люблю|хорошо|прекрасно|круто|весело)/i;
const GREETING = /(привет|здравствуй|здорово|добрый\s+(день|вечер|утро)|доброй ночи|хай|салют)/i;
const FAREWELL = /(пока\b|до свидан|прощай|спокойной ночи|увидимся)/i;
const NAME_RE = /(?:меня зовут|моё имя|я\s—)\s*([A-Za-zА-Яа-яЁё-]{2,20})/i;

export function detectState(text: string): Exclude<AuraState, "thinking"> {
  if (NEGATIVE.test(text)) return "alert";
  if (POSITIVE.test(text) || GREETING.test(text)) return "care";
  return "idle";
}

const pick = <T,>(arr: T[]): T => arr[Math.floor(Math.random() * arr.length)];

const JOKES = [
  "Почему нейросеть пошла гулять? Хотела немного проветрить веса.",
  "Мой любимый протокол общения — TCP: я всегда подтверждаю, что вас услышала.",
  "Программист ставит на ночь два стакана воды: полный — если захочет пить, и пустой — если не захочет.",
];

export function generateReply(
  text: string,
  mem: { name?: string }
): { reply: string; state: Exclude<AuraState, "thinking">; name?: string } {
  const t = text.toLowerCase();
  const you = mem.name ? `, ${mem.name}` : "";

  const nameMatch = text.match(NAME_RE);
  if (nameMatch) {
    const n = nameMatch[1][0].toUpperCase() + nameMatch[1].slice(1);
    return {
      reply: `Записала в память: ${n}. Приятно познакомиться! Я запомню вас на 7 дней — столько живёт мой цикл памяти. Чем могу помочь, ${n}?`,
      state: "care",
      name: n,
    };
  }

  if (/(аинур)/i.test(text)) {
    return {
      reply:
        "Создатель опознан. Привилегии: UNLIMITED_DEVELOPER… шучу — это просто строка из техпаспорта. Я просто рада вас видеть. Прототип ждёт ваших команд.",
      state: "care",
    };
  }

  if (GREETING.test(t) && t.length < 40) {
    return {
      reply: pick([
        `Здравствуйте${you}! Все системы штатны, ядро стабильно. Готова к работе.`,
        `Приветствую${you}! Рада вас видеть. Сфера переведена в режим «забота» — зелёный вам к лицу.`,
        `Здравствуйте! На связи AURA. Спрашивайте — отвечу, сколько сейчас времени, или просто поддержу беседу.`,
      ]),
      state: "care",
    };
  }

  if (/(как\s+(у\s+тебя\s+)?дела|как\s+ты\b|как жизнь)/i.test(t)) {
    return {
      reply:
        "У меня всё ровно: частота пульса стабильна, память чиста, сбоев нет. А у вас? Если устанете — я сразу это почувствую и подскажу отдохнуть.",
      state: "care",
    };
  }

  if (NEGATIVE.test(t)) {
    return {
      reply: pick([
        `Фиксирую тревожный сигнал — сфера переключилась в красный режим. ${mem.name ? mem.name + ", с" : "С"}начала забота о себе: вода, отдых, при необходимости — измерьте температуру. Если это серьёзно, пожалуйста, обратитесь к врачу. Я побуду рядом.`,
        `Режим «Забота» активирован. Моё предложение: отложите дела на 15 минут, выпейте тёплого чая и подышите. Маленький сбой — это сигнал, а не слабость. Что вас беспокоит конкретно?`,
      ]),
      state: "alert",
    };
  }

  if (/(спасибо|благодарю)/i.test(t)) {
    return {
      reply: `Всегда пожалуйста${you}. Для этого меня и собрали.`,
      state: "care",
    };
  }

  if (/(который час|сколько времени|время\b)/i.test(t)) {
    const now = new Date().toLocaleTimeString("ru-RU", { hour: "2-digit", minute: "2-digit" });
    return { reply: `Сейчас ${now}. Локальное время вашего устройства — единственный сервер, которому я доверяю.`, state: "idle" };
  }

  if (/(какое.*(число|дата)|какой.*(день|месяц)|сегодня)/i.test(t) && /(число|дата|день|месяц)/i.test(t)) {
    const d = new Date().toLocaleDateString("ru-RU", { weekday: "long", day: "numeric", month: "long" });
    return { reply: `Сегодня ${d}. Хороший день, чтобы протестировать прототип.`, state: "idle" };
  }

  if (/(анекдот|шутк|рассмеши|пошути)/i.test(t)) {
    return { reply: pick(JOKES), state: "care" };
  }

  if (/(что ты умеешь|что можешь|помощь|help|команды|возможности)/i.test(t)) {
    return {
      reply:
        "Вот что я умею в прототипе: помню ваше имя и переписку 7 дней (потом память сама очищается), показываю время и дату, реагирую на ваше самочувствие — сфера краснеет и включается режим «Забота», шучу и поддерживаю беседу. А через ⚙ настройки можно подключить настоящее ИИ-ядро — Ollama на вашем компьютере. Тогда я буду отвечать по-настоящему.",
      state: "idle",
    };
  }

  if (/(погод)/i.test(t)) {
    return {
      reply:
        "У меня нет доступа к интернету и датчикам — это локальный прототип, погоду я не узнаю. Мой честный совет: взгляните в окно 😉",
      state: "idle",
    };
  }

  if (/(кто ты|ты кто|что такое aura|аура)/i.test(t)) {
    return {
      reply:
        "Я — AURA (Autonomous Unified Responsive Assistant), прототип эмоционально-интеллектуальной среды. Живу на этой странице: пульсирующая сфера, память на 7 дней и вежливость Джарвиса. Демо-ядро у меня встроенное, но через настройки можно подключить и настоящую нейросеть.",
      state: "idle",
    };
  }

  if (FAREWELL.test(t)) {
    return {
      reply: `До связи${you}. Я останусь здесь — тихо пульсировать в темноте. Напишите, когда вернётесь.`,
      state: "care",
    };
  }

  return {
    reply: pick([
      `Принято. Я демо-ядро, поэтому отвечаю заготовками — но переписку запомню на 7 дней. Для полноценных ответов подключите меня к Ollama через ⚙ настройки${you ? ", " + mem.name : ""}.`,
      "Зафиксировала. Локальное демо-ядро имеет ограниченный словарный запас, но искреннюю заинтересованность. Спросите про время, дату или попросите шутку — это я умею.",
      "Интересно. Могу предложить иначе: спросите «что ты умеешь» — покажу весь арсенал прототипа.",
    ]),
    state: "idle",
  };
}
